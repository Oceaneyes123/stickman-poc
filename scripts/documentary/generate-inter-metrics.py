"""Generate src/documentary/core/interMetrics.ts from the bundled Inter variable font.

Advance widths (in em units) for printable ASCII plus a few typographic symbols at
weights 400/600/700/800, so documentary text can be wrapped and checked for overflow
deterministically without measuring in the browser. Requires fontTools.
Run: python scripts/documentary/generate-inter-metrics.py
"""
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "public" / "fonts" / "Inter.ttf"
OUT = ROOT / "src" / "documentary" / "core" / "interMetrics.ts"
CHARS = "".join(chr(c) for c in range(32, 127)) + "·–—•✓×→←…’“”€£"
WEIGHTS = [400, 600, 700, 800]


def widths(weight: int) -> dict[str, float]:
    font = TTFont(FONT)
    axes = {"wght": weight}
    if "opsz" in [a.axisTag for a in font["fvar"].axes]:
        axes["opsz"] = 14
    inst = instancer.instantiateVariableFont(font, axes)
    cmap = inst.getBestCmap()
    upem = inst["head"].unitsPerEm
    hmtx = inst["hmtx"]
    result = {}
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        if glyph is not None:
            result[ch] = round(hmtx[glyph][0] / upem, 4)
    return result


def main():
    tables = {w: widths(w) for w in WEIGHTS}
    lines = [
        "// Generated by scripts/documentary/generate-inter-metrics.py from public/fonts/Inter.ttf.",
        "// Advance widths in em. Do not edit by hand.",
        "export const INTER_WIDTHS: Record<number, Record<string, number>> = {",
    ]
    for weight, table in tables.items():
        lines.append(f"  {weight}: {{")
        for ch, width in table.items():
            key = ch.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    "{key}": {width},')
        lines.append("  },")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(CHARS)} characters x {len(WEIGHTS)} weights)")


if __name__ == "__main__":
    main()
