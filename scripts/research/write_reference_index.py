#!/usr/bin/env python3
"""Write research/channels/reference-index.md from the corpus."""

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVID = ROOT / "research" / "evidence"
OUT = ROOT / "research" / "channels" / "reference-index.md"

SAMPLED = {
    "h6fcK_fRYaI": "3, 12, 25, 40, 60, 80 s",
    "1zjcZ661ups": "4, 20, 45, 75, 150, 300, 480, 660 s",
    "6mRbDEtDoyA": "5, 25, 60, 120, 300, 600, 900, 1020 s",
    "n9HAAFBT3AA": "5, 20, 50, 90, 150, 260, 380, 470 s",
    "1AF04-V4Yao": "5, 20, 45, 80, 140, 250, 350, 480 s",
    "pCBP4M08ndE": "5, 25, 60, 100, 180, 280, 360, 445 s",
    "2yFCyPX3kT0": "4, 15, 40, 70, 140, 240, 330, 395 s (only 70 s read)",
}
CUTS = {"1zjcZ661ups": "144", "6mRbDEtDoyA": "283", "n9HAAFBT3AA": "62",
        "2yFCyPX3kT0": "90", "1AF04-V4Yao": "114", "pCBP4M08ndE": "5"}


def hms(s):
    if not s:
        return "—"
    s = int(s)
    return f"{s // 60}:{s % 60:02d}" if s < 3600 else f"{s // 3600}:{(s % 3600) // 60:02d}:{s % 60:02d}"


def main():
    stats = json.loads((EVID / "channel-stats.json").read_text(encoding="utf-8"))
    recs = [json.loads(Path(p).read_text(encoding="utf-8")) for p in sorted(glob.glob(str(EVID / "*" / "*.json")))]

    L = ["# Reference index", "",
         "Every video cited anywhere in `research/channels/` and `research/playbooks/`, with the",
         "exact evidence available for it. Generated by `scripts/research/write_reference_index.py`",
         "from `research/evidence/` — regenerate rather than hand-editing.", "",
         "**Evidence key**", "",
         "- `captions` — YouTube's own timed captions, retrieved with youtube-transcript-api.",
         "- `asr` — locally transcribed (faster-whisper small) because YouTube blocked or disabled captions; punctuation restored by the model, so names and numbers can be misheard.",
         "- `none` — metadata only: title, views, runtime. No script or visual claims may cite it.",
         "- `sampled` — frames extracted and read; timestamps listed.",
         "- `cuts` — ffmpeg scene-detection count at threshold 0.35 (see `editing-pacing.md` for the method's error bars).",
         "", "## Channels", "",
         "| Channel | Handle | Subscribers | Videos |", "|---|---|---:|---:|"]
    for h, v in sorted(stats.items(), key=lambda kv: kv[1].get("name", "")):
        L.append(f"| {v.get('name', h)} | {v.get('handle', h)} | {v.get('subs', '—')} | {v.get('vids', '—')} |")

    L += ["", "## Videos", ""]
    by = {}
    for r in recs:
        by.setdefault(r["channel"], []).append(r)
    for ch in sorted(by):
        L += [f"### {ch}", "",
              "| Video | URL | Views | Length | Evidence |",
              "|---|---|---:|---:|---|"]
        for r in sorted(by[ch], key=lambda x: -(x.get("views") or 0)):
            ev = []
            if r.get("segments"):
                ev.append(r.get("source") or "captions")
            else:
                ev.append("none")
            if r["video_id"] in SAMPLED:
                ev.append(f"sampled {SAMPLED[r['video_id']]}")
            if r["video_id"] in CUTS:
                ev.append(f"cuts {CUTS[r['video_id']]}")
            L.append(f"| {r['title'][:80].replace('|', '/')} | {r['url']} | {r.get('views') or 0:,} | "
                     f"{hms(r.get('duration_s'))} | {'; '.join(ev)} |")
        L.append("")

    L += ["## Local evidence files", "",
          "- `research/evidence/index.json` — ranked video lists per channel.",
          "- `research/evidence/metrics.json` — per-video word counts, wpm, hook windows, phrase counts.",
          "- `research/evidence/tables.md` — generated corpus tables.",
          "- `research/evidence/visual-observations.md` — what each sampled frame showed.",
          "- `research/evidence/frames/` — contact sheets and individual stills.",
          "- `research/evidence/channel-stats.json` — subscriber counts read from channel pages.",
          "", "## Regeneration", "",
          "```bash",
          "python scripts/research/fetch_evidence.py --count 3 @Handle …",
          "python scripts/research/transcribe_audio.py --missing      # only where captions are blocked",
          "python scripts/research/metrics.py",
          "python scripts/research/report_tables.py",
          "python scripts/research/write_reference_index.py",
          "```"]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
