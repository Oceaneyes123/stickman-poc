#!/usr/bin/env python3
"""Emit markdown evidence tables from research-evidence/ for the research docs."""

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVID = ROOT / "research-evidence"
stats = json.loads((EVID / "channel-stats.json").read_text(encoding="utf-8"))


def hms(s):
    if not s:
        return "—"
    s = int(s)
    return f"{s // 60}:{s % 60:02d}" if s < 3600 else f"{s // 3600}:{(s % 3600) // 60:02d}:{s % 60:02d}"


def main():
    recs = []
    for p in sorted(glob.glob(str(EVID / "*" / "*.json"))):
        recs.append(json.loads(Path(p).read_text(encoding="utf-8")))
    by = {}
    for r in recs:
        by.setdefault(r["channel"], []).append(r)

    lines = ["# Evidence tables", "", "Generated by `scripts/research/report_tables.py`. Do not hand-edit.", ""]
    lines += ["## Channels", "", "| Channel | Handle | Subscribers | Videos on channel | Corpus videos | Captions |",
              "|---|---|---:|---:|---:|---|"]
    for ch, rs in sorted(by.items()):
        st = next((v for v in stats.values() if v.get("name", "").startswith(ch.split(" –")[0][:18])), {})
        cap = sum(1 for r in rs if r.get("segments"))
        lines.append(f"| {ch} | {rs[0]['handle']} | {st.get('subs', '—')} | {st.get('vids', '—')} | {len(rs)} | {cap}/{len(rs)} |")

    lines += ["", "## Videos", "",
              "| Channel | Title | Views | Duration | Captions | Words | Source |",
              "|---|---|---:|---:|---|---:|---|"]
    for ch, rs in sorted(by.items()):
        for r in sorted(rs, key=lambda x: -(x.get("views") or 0)):
            words = sum(len(s["text"].split()) for s in (r.get("segments") or []))
            src = r.get("source") or ("captions" if r.get("segments") else (r.get("caption_error") or "—"))
            lines.append(f"| {ch} | {r['title'][:70].replace('|', '/')} | {r.get('views') or 0:,} | "
                         f"{hms(r.get('duration_s'))} | {'yes' if r.get('segments') else 'no'} | {words or '—'} | {src} |")

    (EVID / "tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:8]))
    print(f"... wrote {len(lines)} lines to research-evidence/tables.md")


if __name__ == "__main__":
    main()
