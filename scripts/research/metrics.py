#!/usr/bin/env python3
"""Deterministic metrics over the fetched caption corpus.

Everything here is counted from research/evidence/*/*.json. Caption text is
auto-generated by YouTube, so punctuation and speaker labels are unreliable;
the report prints the caveat with the numbers.

    python metrics.py  -> research/evidence/metrics.json + a markdown table
"""

import glob
import json
import re
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVID = ROOT / "research" / "evidence"
WINDOWS = [5, 15, 30, 60]
ABBREV = re.compile(r"\b(Mr|Mrs|Ms|Dr|U\.S|U\.K|vs|etc|e\.g|i\.e)\.", re.I)


def sentences(text):
    t = ABBREV.sub(lambda m: m.group(0).replace(".", "<DOT>"), text)
    parts = re.split(r"(?<=[.!?])\s+", t)
    return [p.replace("<DOT>", ".").strip() for p in parts if p.strip()]


def text_until(segments, sec):
    return " ".join(s["text"] for s in segments if s["t"] < sec).strip()


def analyse(rec):
    segs = rec.get("segments") or []
    if not segs:
        return None
    body = " ".join(s["text"] for s in segs).strip()
    words = body.split()
    n = len(words)
    sents = sentences(body)
    lens = [len(s.split()) for s in sents if s.split()]
    span = max(s["t"] + s["d"] for s in segs) or 1.0
    low = body.lower()
    return {
        "video_id": rec["video_id"],
        "channel": rec["channel"],
        "title": rec["title"],
        "views": rec["views"],
        "words": n,
        "caption_span_s": round(span, 1),
        "wpm": round(n / (span / 60), 1) if span else None,
        "sentences": len(sents),
        "mean_sentence_words": round(st.mean(lens), 1) if lens else None,
        "median_sentence_words": round(st.median(lens), 1) if lens else None,
        "short_sentence_share": round(sum(1 for x in lens if x <= 8) / len(lens), 3) if lens else None,
        "long_sentence_share": round(sum(1 for x in lens if x >= 30) / len(lens), 3) if lens else None,
        "questions_per_100w": round(100 * body.count("?") / n, 2),
        "contractions_per_100w": round(100 * len(re.findall(r"\b\w+'(t|s|re|ll|ve|d|m)\b", low)) / n, 2),
        "you_per_100w": round(100 * len(re.findall(r"\byou\b|\byour\b", low)) / n, 2),
        "i_per_100w": round(100 * len(re.findall(r"\bi\b|\bmy\b|\bme\b", low)) / n, 2),
        "hook": {f"{w}s": text_until(segs, w) for w in WINDOWS},
    }


def selftest():
    """One runnable check for the parsing logic. python metrics.py --selftest"""
    segs = [{"t": 0.0, "d": 10.0, "text": "You live on the 30th floor."},
            {"t": 10.0, "d": 10.0, "text": "Until tonight, that was the worst thing about your flat."}]
    rec = {"video_id": "x", "channel": "c", "title": "t", "views": 1, "segments": segs}
    a = analyse(rec)
    assert a["words"] == 16, a["words"]                       # 6 + 10 words
    assert a["wpm"] == round(16 / (20 / 60), 1), a["wpm"]     # span 20 s
    assert a["sentences"] == 2, a["sentences"]
    assert a["mean_sentence_words"] == 8.0, a["mean_sentence_words"]
    assert a["you_per_100w"] == round(100 * 2 / 16, 2), a["you_per_100w"]  # you, your
    assert sentences("Mr. Smith left. He ran!") == ["Mr. Smith left.", "He ran!"]
    assert a["hook"]["5s"] == "You live on the 30th floor.", a["hook"]["5s"]
    print("metrics selftest ok")


def main():
    if "--selftest" in sys.argv:
        selftest()
        return
    rows, hooks = [], []
    for p in sorted(glob.glob(str(EVID / "*" / "*.json"))):
        rec = json.loads(Path(p).read_text(encoding="utf-8"))
        a = analyse(rec)
        if not a:
            rows.append({"video_id": rec["video_id"], "channel": rec["channel"], "title": rec["title"],
                         "views": rec["views"], "unavailable": rec.get("caption_error")})
            continue
        rows.append(a)
        hooks.append({"channel": a["channel"], "title": a["title"], "video_id": a["video_id"], **a["hook"]})

    out = {
        "note": ("Counts come from YouTube auto-captions. Punctuation, speaker labels and "
                 "numbers are recognition output, not the creator's script. wpm uses caption "
                 "span, so it includes pauses and music-only gaps."),
        "videos": rows,
        "hooks": hooks,
    }
    (EVID / "metrics.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")

    ok = [r for r in rows if "words" in r]
    print(f"videos with captions: {len(ok)}/{len(rows)}")
    print(f"{'channel':22} {'videos':>6} {'words':>7} {'wpm':>6} {'meanSent':>8} {'q/100w':>7} {'you/100w':>8}")
    by = {}
    for r in ok:
        by.setdefault(r["channel"], []).append(r)
    for ch, rs in sorted(by.items()):
        print(f"{ch[:22]:22} {len(rs):>6} {round(st.mean(x['words'] for x in rs)):>7} "
              f"{round(st.mean(x['wpm'] for x in rs),1):>6} {round(st.mean(x['mean_sentence_words'] for x in rs),1):>8} "
              f"{round(st.mean(x['questions_per_100w'] for x in rs),2):>7} {round(st.mean(x['you_per_100w'] for x in rs),2):>8}")


if __name__ == "__main__":
    main()
