export const allocationParts = (stage: 1 | 2 | 3) =>
  example.upgrades.slice(0, stage).map((item) => item.amount);
export const allocationRemainder = (stage: 1 | 2 | 3) =>
  example.raise - allocationParts(stage).reduce((a, b) => a + b, 0);

